# -*- coding: utf-8 -*-
"""stringResources (12 idiomas) y src/strings.ts.

Fuente: stringResources/en-US y es-ES, que se editan a mano. Las demás se generan por TEXTO inglés:
tools/i18n_propias.json (escritas para este visual) manda sobre tools/i18n_table.json (las que usan
los otros visuales de TCViz). Orden de cada fila: pt, fr, de, it, nl, pl, ja, zh, ko.
Ejecutar desde la raíz:  python tools/i18n.py
"""
import io, json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
L = ["pt-BR", "fr-FR", "de-DE", "it-IT", "nl-NL", "pl-PL", "ja-JP", "zh-CN", "ko-KR"]
# Sin traducir: los nombres de los estilos son nombres propios y los símbolos valen en todo idioma.
IGUAL = {"> {0}", "≤ {0}", "{0} – {1}"}


def lee(*p):
    return json.load(io.open(os.path.join(ROOT, *p), encoding="utf-8"))


def main():
    en, es = lee("stringResources", "en-US", "resources.resjson"), lee("stringResources", "es-ES", "resources.resjson")
    if set(en) != set(es):
        raise SystemExit("en-US y es-ES no tienen las mismas claves: %s" % sorted(set(en) ^ set(es)))
    T = {**lee("tools", "i18n_table.json"), **lee("tools", "i18n_propias.json")}
    propio = lambda k: k.startswith("Enum_style_") and k != "Enum_style_report"
    falta = sorted({v for k, v in en.items() if v not in T and v not in IGUAL and not propio(k)})
    if falta:
        raise SystemExit("Sin traducción: " + " | ".join(falta))
    malas = [v for v, fila in T.items() if len(fila) != len(L) or any(("{%d}" % i in v) != ("{%d}" % i in x) for x in fila for i in range(4))]
    if malas:
        raise SystemExit("Fila mal formada: " + " | ".join(malas))
    out = {"en-US": en, "es-ES": es}
    for i, lang in enumerate(L):
        out[lang] = {k: (v if v in IGUAL or propio(k) else T[v][i]) for k, v in en.items()}
    # Portugués europeo: mismas claves, con los términos que cambian respecto al de Brasil.
    pt = {"Compartilham": "Partilham", "grade": "grelha", "porcentagem": "percentagem", "relatório": "relatório"}
    out["pt-PT"] = {}
    for k, v in out["pt-BR"].items():
        for a, b in pt.items():
            v = v.replace(a, b)
        out["pt-PT"][k] = v
    for lang, d in out.items():
        p = os.path.join(ROOT, "stringResources", lang)
        os.makedirs(p, exist_ok=True)
        io.open(os.path.join(p, "resources.resjson"), "w", encoding="utf-8", newline="\n").write(json.dumps(d, ensure_ascii=False, indent=2))
    # Bundle: claves que NO están en capabilities (Desktop no las traduce con getDisplayName).
    capstxt = io.open(os.path.join(ROOT, "capabilities.json"), encoding="utf-8").read()
    runtime = sorted(k for k in en if '"%s"' % k not in capstxt)
    tabla = {lang: {k: d[k] for k in runtime if d[k] != en[k]} for lang, d in out.items() if lang != "en-US"}
    ts = ["/**",
          " * Translations of the text the visual writes itself (notices, tooltips, range bar).",
          " * Power BI Desktop only resolves through getDisplayName the keys declared in capabilities.json,",
          " * so these travel in the bundle. Generated by tools/i18n.py: do not edit by hand.",
          " */",
          "export const STRINGS: Record<string, Record<string, string>> = " + json.dumps(tabla, ensure_ascii=False, indent=4) + ";", ""]
    io.open(os.path.join(ROOT, "src", "strings.ts"), "w", encoding="utf-8", newline="\n").write("\n".join(ts))
    print(len(en), "claves ·", len(out), "idiomas ·", len(runtime), "en el bundle")


if __name__ == "__main__":
    main()
